#!/usr/bin/env python3
"""Build the Plover Grafana dashboard (JSON) and its ConfigMap (what Argo CD syncs; the kps Grafana sidecar loads it).
Same panels on every cloud (🔁 Lab 02 panels + product panels + live $/1M tokens). Re-run after editing PANELS:
  python3 observability/build_dashboard.py   ->  observability/dashboards/plover.json + observability/grafana-dashboard.yaml
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
DS = {"type": "prometheus", "uid": "${datasource}"}
# (row, title, type, unit, [(expr, legend)])
PANELS = [
    ("Product - Plover API", None, None, None, None),
    (None, "Summaries/s by variant and outcome", "timeseries", "reqps", [('plv:api_requests:rate5m{route="summarize"}', "{{variant}} {{outcome}}")]),
    (None, "Schema-valid ratio by variant (canary gate)", "timeseries", "percentunit",
     [('sum by (variant) (rate(plover_api_schema_valid_total{valid="true"}[5m])) / clamp_min(sum by (variant) (rate(plover_api_schema_valid_total[5m])), 1e-9)', "{{variant}}")]),
    (None, "Prompt tokens per summary (LoRA payoff)", "timeseries", "none",
     [("sum by (variant) (rate(plover_api_prompt_tokens_total[5m])) / clamp_min(sum by (variant) (rate(plover_api_schema_valid_total[5m])), 1e-9)", "{{variant}}")]),
    (None, "API latency p95 (s)", "timeseries", "s", [("plv:api_latency_seconds:p95_5m", "{{route}}")]),
    ("NIM - Lab 02 panels", None, None, None, None),
    (None, "TTFT p95 (s)", "timeseries", "s", [("plv:llm_ttft_seconds:p95_5m", "{{service}}")]),
    (None, "ITL p95 (s)", "timeseries", "s", [("plv:llm_itl_seconds:p95_5m", "{{service}}")]),
    (None, "Queue depth (HPA signal)", "timeseries", "none", [("plv:llm_requests_waiting", "waiting {{service}}"), ("plv:llm_requests_running", "running {{service}}")]),
    (None, "KV-cache usage", "timeseries", "percentunit", [("plv:llm_kv_cache_usage", "{{service}}")]),
    (None, "Output tokens/s", "timeseries", "none", [("plv:llm_generation_tokens:rate1m", "{{service}}")]),
    (None, "Prefix-cache hit ratio (long style prompt)", "timeseries", "percentunit", [("plv:llm_prefix_cache_hit_ratio:5m", "{{service}}")]),
    ("GPU and cost", None, None, None, None),
    (None, "GPU power (W) - empty on SR-IOV vGPU (Azure NCv6)", "timeseries", "watt", [("plv:gpu_power_watts", "{{Hostname}}")]),
    (None, "Tokens per joule", "stat", "none", [("plv:cluster_generated_tokens_per_joule:5m", "")]),
    (None, "Live $ per 1M output tokens (set gpu_hourly)", "stat", "currencyUSD",
     [("$gpu_hourly / clamp_min(sum(rate(vllm:generation_tokens_total[5m])) * 3600, 1e-9) * 1e6", "")]),
    (None, "DRAM active (bandwidth-bound decode)", "timeseries", "percentunit", [("plv:gpu_dram_active", "{{Hostname}} {{GPU_I_PROFILE}}")]),
]


def build():
    panels, y, x, pid = [], 0, 0, 1
    for row, title, ptype, unit, targets in PANELS:
        if row:
            if x:
                y, x = y + 8, 0
            panels.append({"id": pid, "type": "row", "title": row, "collapsed": False, "gridPos": {"h": 1, "w": 24, "x": 0, "y": y}, "panels": []})
            y += 1
        else:
            w = 6 if ptype == "stat" else 12
            if x + w > 24:
                y, x = y + 8, 0
            panels.append({"id": pid, "type": ptype, "title": title, "datasource": DS, "gridPos": {"h": 8, "w": w, "x": x, "y": y},
                           "targets": [{"refId": chr(65 + i), "expr": e, "legendFormat": lf, "datasource": DS} for i, (e, lf) in enumerate(targets)],
                           "fieldConfig": {"defaults": {"unit": unit}, "overrides": []}, "options": {}})
            x += w
        pid += 1
    return {"title": "Plover - multi-cloud NIM (Lab 04)", "uid": "plv-plover", "editable": True, "schemaVersion": 39, "version": 1,
            "refresh": "30s", "time": {"from": "now-1h", "to": "now"}, "tags": ["plover", "nvidia", "nim", "multi-cloud"],
            "templating": {"list": [
                {"name": "datasource", "type": "datasource", "query": "prometheus", "label": "Prometheus", "current": {}, "hide": 0, "refresh": 1, "regex": "", "options": []},
                {"name": "gpu_hourly", "type": "textbox", "label": "GPU node $/hour", "query": "0.68",
                 "current": {"text": "0.68", "value": "0.68"}, "hide": 0}]},
            "annotations": {"list": []}, "panels": panels}


def main():
    dash = build()
    js = json.dumps(dash, indent=1)
    (HERE / "dashboards" / "plover.json").write_text(js + "\n")
    cm = ["# GENERATED by observability/build_dashboard.py - edit PANELS there, not this file.",
          "apiVersion: v1", "kind: ConfigMap", "metadata:", "  name: plv-grafana-dashboard", "  namespace: monitoring",
          "  labels:", '    grafana_dashboard: "1"', "data:", "  plover.json: |"]
    cm += ["    " + line for line in js.splitlines()]
    (HERE / "grafana-dashboard.yaml").write_text("\n".join(cm) + "\n")
    print(f"{len(dash['panels'])} panels -> observability/dashboards/plover.json, observability/grafana-dashboard.yaml")


if __name__ == "__main__":
    main()
